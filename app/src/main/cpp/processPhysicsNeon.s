/*
 * ============================================================================
 * نام تابع: update_all_fruits_neon
 * هدف: به‌روزرسانی فیزیک تمام میوه‌ها (حرکت، شتاب، اصطکاک و برخورد) به صورت موازی
 * * ورودی‌های سیستمی (Arguments):
 * -----------------------------
 * x0 : آدرس شروع بافر میوه‌ها (هر میوه 20 بایت شامل: x, y, vx, vy, rotation)
 * x1 : تعداد کل میوه‌ها جهت پردازش (Count)
 * s0 : ضریب زمان یا سرعت کلی انیمیشن (speedMultiplier)
 * s1 : عرض کل صفحه نمایش (screenWidth) جهت محاسبه مرزها
 * ============================================================================
 */

.text
.align 4
.global update_all_fruits_neon

update_all_fruits_neon:
    /* --- ۱. حفظ ریجیسترهای Callee-saved (ذخیره در پشته برای جلوگیری از کرش) --- */

 * 1. با متد Pre-indexed (!) ابتدا SP را 64 بایت کم می‌کنیم تا فضا رزرو شود.
 * 2. ریجیسترهای d8 تا d15 (هر کدام 8 بایت) را جفت‌جفت (stp) ذخیره می‌کنیم.
 * طبق استاندارد ARM64، حفظ این ریجیسترها (Callee-saved) برای جلوگیری از کرش اجباری است.
 */
    /* باز کردن فضای 64 بایتی در پشته و ذخیره ریجیسترهای d8 و d9 */
    stp d8, d9, [sp, #-64]!
    /* ذخیره ریجیسترهای d10 و d11 در آفست 16 بایتی پشته */
    stp d10, d11, [sp, #16]
    /* ذخیره ریجیسترهای d12 و d13 در آفست 32 بایتی پشته */
    stp d12, d13, [sp, #32]
    /* ذخیره ریجیسترهای d14 و d15 در آفست 48 بایتی پشته */
    stp d14, d15, [sp, #48]

    /* --- ۲. آماده‌سازی ثوابت در وکتورها (تبدیل اعداد تکی به بردار 4 تایی) --- */

    /* کپی کردن ضریب سرعت ورودی (s0) به s10 */
    fmov s10, s0
    /* تکثیر (Broadcast) ضریب سرعت در تمام 4 کانال وکتور v10 برای محاسبات موازی */
    dup v10.4s, v10.s[0]

    /* مقداردهی عدد 3.0 برای جاذبه (Gravity) */
    mov w2, #0x40400000
    fmov s3, w2
    /* اعمال ضریب سرعت به جاذبه و ذخیره در s11 */
    fmul s11, s3, s10
    /* تکثیر جاذبه در تمام کانال‌های v11 */
    dup v11.4s, v11.s[0]

    /* بارگذاری ضریب اصطکاک (Drag) معادل 0.985 */
    ldr w2, =0x3f7c28f6
    fmov s12, w2
    /* تکثیر اصطکاک در تمام کانال‌های v12 */
    dup v12.4s, v12.s[0]

    /* مقداردهی سرعت چرخش 5.0 (Rotation Step) */
    mov w2, #0x40a00000
    fmov s3, w2
    /* اعمال ضریب سرعت به گام چرخش و ذخیره در s13 */
    fmul s13, s3, s10
    /* تکثیر مقدار چرخش در v13 */
    dup v13.4s, v13.s[0]

    /* مقداردهی حاشیه دیوارها (Margin) معادل 80.0 پیکسل */
    mov w2, #0x42a00000
    fmov s14, w2
    /* تکثیر حاشیه دیوار چپ در v14 */
    dup v14.4s, v14.s[0]

    /* محاسبه مختصات دیوار راست: (عرض صفحه - حاشیه) */
    fsub s15, s1, s14
    /* تکثیر مختصات دیوار راست در v15 */
    dup v15.4s, v15.s[0]

    /* بارگذاری ضریب برگشت (Bounce) معادل -0.7 */
    ldr w2, =0xbf333333
    fmov s16, w2
    /* تکثیر ضریب برگشت در v16 برای استفاده در برخوردها */
    dup v16.4s, v16.s[0]

physics_loop:
    /* بررسی اینکه آیا حداقل 4 میوه برای پردازش موازی باقی مانده است یا خیر */
    cmp x1, #4
    /* اگر کمتر از 4 میوه مانده، به بخش پاکسازی (پردازش تکی) برو */
    b.lt single_fruit_cleanup

    /* --- ۳. بارگذاری ۴ میوه (تبدیل ساختار آرایه به ساختار برداری) --- */

    /* بارگذاری داده‌های میوه اول در ایندکس 0 رجیسترهای v0 تا v4 */
;    4 بایت چون هر float 32 بیت است
    ld1 {v0.s}[0], [x0], #4  /* بارگذاری X میوه 1 */
    ld1 {v1.s}[0], [x0], #4  /* بارگذاری Y میوه 1 */
    ld1 {v2.s}[0], [x0], #4  /* بارگذاری VX میوه 1 */
    ld1 {v3.s}[0], [x0], #4  /* بارگذاری VY میوه 1 */
    ld1 {v4.s}[0], [x0], #4  /* بارگذاری Rotation میوه 1 */

    /* بارگذاری داده‌های میوه دوم در ایندکس 1 (هر بار 4 بایت پوینتر جلو می‌رود) */
    ld1 {v0.s}[1], [x0], #4  /* بارگذاری X میوه 2 */
    ld1 {v1.s}[1], [x0], #4  /* بارگذاری Y میوه 2 */
    ld1 {v2.s}[1], [x0], #4  /* بارگذاری VX میوه 2 */
    ld1 {v3.s}[1], [x0], #4  /* بارگذاری VY میوه 2 */
    ld1 {v4.s}[1], [x0], #4  /* بارگذاری Rotation میوه 2 */

    /* بارگذاری داده‌های میوه سوم در ایندکس 2 */
    ld1 {v0.s}[2], [x0], #4  /* بارگذاری X میوه 3 */
    ld1 {v1.s}[2], [x0], #4  /* بارگذاری Y میوه 3 */
    ld1 {v2.s}[2], [x0], #4  /* بارگذاری VX میوه 3 */
    ld1 {v3.s}[2], [x0], #4  /* بارگذاری VY میوه 3 */
    ld1 {v4.s}[2], [x0], #4  /* بارگذاری Rotation میوه 3 */

    /* بارگذاری داده‌های میوه چهارم در ایندکس 3 */
    ld1 {v0.s}[3], [x0], #4  /* بارگذاری X میوه 4 */
    ld1 {v1.s}[3], [x0], #4  /* بارگذاری Y میوه 4 */
    ld1 {v2.s}[3], [x0], #4  /* بارگذاری VX میوه 4 */
    ld1 {v3.s}[3], [x0], #4  /* بارگذاری VY میوه 4 */
    ld1 {v4.s}[3], [x0], #4  /* بارگذاری Rotation میوه 4 */

    /* --- ۴. محاسبات فیزیک (اجرای همزمان برای هر 4 میوه) --- */

;مخفف Floating-point Multiply-Add. این دستور v2 * v10 را حساب کرده و با مقدار قبلی v0 جمع می‌کند.
    /* به‌روزرسانی X: (x = x + vx * speedMultiplier) */
    fmla v0.4s, v2.4s, v10.4s
    /* به‌روزرسانی Y: (y = y + vy * speedMultiplier) */
    fmla v1.4s, v3.4s, v10.4s
    /* اعمال جاذبه به سرعت عمودی: (vy = vy + gravity) */
    fadd v3.4s, v3.4s, v11.4s
    /* اعمال اصطکاک هوا به سرعت افقی: (vx = vx * drag) */
    fmul v2.4s, v2.4s, v12.4s
    /* به‌روزرسانی چرخش: (rotation = rotation + rotStep) */
    fadd v4.4s, v4.4s, v13.4s

    /* --- ۵. مدیریت برخورد --- */

    /* مقایسه X با مرز چپ: ایجاد ماسک برای میوه‌هایی که از سمت چپ خارج شده‌اند */
    fcmgt v20.4s, v14.4s, v0.4s
    /* مقایسه X با مرز راست: ایجاد ماسک برای میوه‌هایی که از سمت راست خارج شده‌اند */
    fcmgt v21.4s, v0.4s, v15.4s
    /* ترکیب دو ماسک (OR): شناسایی هر نوع برخورد با دیواره‌های جانبی */
    orr v22.16b, v20.16b, v21.16b

 * 1. ابتدا سرعت معکوس (Bounce) را برای همه 4 میوه محاسبه کرده و در v23 قرار می‌دهیم.
 * 2. دستور BIT (Bitwise Insert if True) بر اساس ماسک (v20, v21, v22) عمل می‌کند:
 * - اگر بیت ماسک 1 باشد (برخورد رخ داده): مقدار جدید (دیوار یا سرعت معکوس) جایگزین می‌شود.
 * - اگر بیت ماسک 0 باشد (برخورد رخ نداده): مقدار فعلی دست‌نخورده باقی می‌ماند.
 * این روش باعث حذف دستورات شرطی (if) شده و سرعت پردازش را به شدت بالا می‌برد.

    /* محاسبه سرعت معکوس (Bounce): ضرب سرعت افقی در -0.7 */
    fmul v23.4s, v2.4s, v16.4s
    /* اگر برخورد رخ داده، سرعت معکوس را در رجیستر vx جایگذاری کن */
    bit v2.16b, v23.16b, v22.16b
    /* اگر از دیوار چپ رد شده، موقعیت X را دقیقاً روی خط Margin قرار بده */
    bit v0.16b, v14.16b, v20.16b
    /* اگر از دیوار راست رد شده، موقعیت X را دقیقاً روی مرز سمت راست قرار بده */
    bit v0.16b, v15.16b, v21.16b

    // --- ۶. ذخیره‌سازی (برگرداندن نتایج به حافظه RAM) ---

        /* بازگرداندن پوینتر x0 به ابتدای بلوک 4 میوه‌ای (4 میوه * 20 بایت = 80 بایت) */
        /* چون موقع لود کردن 80 بایت جلو رفته بودیم، حالا باید برگردیم تا روی همان میوه‌ها بنویسیم */
        sub x0, x0, #80

        /* ذخیره داده‌های میوه اول (ایندکس 0 از هر وکتور) و پیشروی خودکار پوینتر */
        st1 {v0.s}[0], [x0], #4    /* ذخیره X جدید میوه 1 */
        st1 {v1.s}[0], [x0], #4    /* ذخیره Y جدید میوه 1 */
        st1 {v2.s}[0], [x0], #4    /* ذخیره VX جدید میوه 1 */
        st1 {v3.s}[0], [x0], #4    /* ذخیره VY جدید میوه 1 */
        st1 {v4.s}[0], [x0], #4    /* ذخیره چرخش جدید میوه 1 */

        /* ذخیره داده‌های میوه دوم (ایندکس 1) */
        st1 {v0.s}[1], [x0], #4    /* ذخیره X جدید میوه 2 */
        st1 {v1.s}[1], [x0], #4    /* ذخیره Y جدید میوه 2 */
        st1 {v2.s}[1], [x0], #4    /* ذخیره VX جدید میوه 2 */
        st1 {v3.s}[1], [x0], #4    /* ذخیره VY جدید میوه 2 */
        st1 {v4.s}[1], [x0], #4    /* ذخیره چرخش جدید میوه 2 */

        /* ذخیره داده‌های میوه سوم (ایندکس 2) */
        st1 {v0.s}[2], [x0], #4    /* ذخیره X جدید میوه 3 */
        st1 {v1.s}[2], [x0], #4    /* ذخیره Y جدید میوه 3 */
        st1 {v2.s}[2], [x0], #4    /* ذخیره VX جدید میوه 3 */
        st1 {v3.s}[2], [x0], #4    /* ذخیره VY جدید میوه 3 */
        st1 {v4.s}[2], [x0], #4    /* ذخیره چرخش جدید میوه 3 */

        /* ذخیره داده‌های میوه چهارم (ایندکس 3) */
        st1 {v0.s}[3], [x0], #4    /* ذخیره X جدید میوه 4 */
        st1 {v1.s}[3], [x0], #4    /* ذخیره Y جدید میوه 4 */
        st1 {v2.s}[3], [x0], #4    /* ذخیره VX جدید میوه 4 */
        st1 {v3.s}[3], [x0], #4    /* ذخیره VY جدید میوه 4 */
        st1 {v4.s}[3], [x0], #4    /* ذخیره چرخش جدید میوه 4 */

        /* کم کردن 4 واحد از تعداد کل میوه‌ها (چون یک بلوک 4 تایی تمام شد) */
        sub x1, x1, #4
        /* پرش به ابتدای حلقه فیزیک برای پردازش 4 میوه بعدی */
        b physics_loop

    single_fruit_cleanup:
        /* بخش پاک‌سازی: اگر تعداد میوه‌ها صفر است، مستقیماً به پایان تابع برو */
        cbz x1, physics_end

        /* بارگذاری تک‌تک ویژگی‌های یک میوه (زمانی که کمتر از 4 تا باقی مانده) */
        ldr s0, [x0]               /* بارگذاری X */
        ldr s1, [x0, #4]           /* بارگذاری Y */
        ldr s2, [x0, #8]           /* بارگذاری VX */
        ldr s3, [x0, #12]          /* بارگذاری VY */
        ldr s4, [x0, #16]          /* بارگذاری Rotation */

        /* محاسبه موقعیت جدید X با استفاده از دستور ضرب و جمع (x = x + vx * dt) */
        fmadd s0, s2, s10, s0
        /* محاسبه موقعیت جدید Y با استفاده از دستور ضرب و جمع (y = y + vy * dt) */
        fmadd s1, s3, s10, s1

;    به‌روزرسانی سایر پارامترهای فیزیکی برای تک میوه ---

       /* اعمال جاذبه به سرعت عمودی: (vy = vy + gravity) */
       fadd s3, s3, s11

       /* اعمال اصطکاک به سرعت افقی: (vx = vx * drag) */
       fmul s2, s2, s12

       /* به‌روزرسانی زاویه چرخش: (rotation = rotation + rotStep) */
       fadd s4, s4, s13

       /* مقایسه موقعیت X با مرز دیوار چپ (Margin) */
       fcmp s0, s14
       /* اگر X کمتر از حاشیه بود، به بخش برخورد با چپ برو */
       b.lt collide_left

       /* مقایسه موقعیت X با مرز دیوار راست (ScreenWidth - Margin) */
       fcmp s0, s15
       /* اگر X بزرگتر از حاشیه راست بود، به بخش برخورد با راست برو */
       b.gt collide_right

       /* اگر برخوردی نبود، مستقیماً برای ذخیره‌سازی برو */
       b store_single

   collide_left:
       /* قرار دادن میوه دقیقاً روی مرز دیوار چپ (برای جلوگیری از گیر کردن در دیوار) */
       fmov s0, s14
       /* معکوس کردن سرعت افقی و اعمال ضریب Bounce (vx = vx * -0.7) */
       fmul s2, s2, s16
       /* پرش به بخش ذخیره */
       b store_single

   collide_right:
       /* قرار دادن میوه دقیقاً روی مرز دیوار راست */
       fmov s0, s15
       /* معکوس کردن سرعت افقی و اعمال ضریب Bounce (vx = vx * -0.7) */
       fmul s2, s2, s16

   store_single:
       /* ذخیره X جدید در حافظه (آفست 0) */
       str s0, [x0]
       /* ذخیره Y جدید در حافظه (آفست 4) */
       str s1, [x0, #4]
       /* ذخیره سرعت افقی جدید در حافظه (آفست 8) */
       str s2, [x0, #8]
       /* ذخیره سرعت عمودی جدید در حافظه (آفست 12) */
       str s3, [x0, #12]
       /* ذخیره زاویه چرخش جدید در حافظه (آفست 16) */
       str s4, [x0, #16]

       /* جلو بردن پوینتر حافظه به اندازه 20 بایت برای میوه بعدی */
       add x0, x0, #20
       /* کم کردن یک واحد از شمارنده تعداد میوه‌های باقی‌مانده */
       sub x1, x1, #1
       /* تکرار حلقه برای میوه بعدی در بخش پاک‌سازی */
       b single_fruit_cleanup

   physics_end:
       /* --- بازیابی ریجیسترهای حفظ شده (Restore Callee-saved Registers) --- */

 * 1. با دستور ldp مقادیر قبلی را به ریجیسترها برمی‌گردانیم.
 * 2. در خط آخر با متد Post-indexed، مقدار SP را 64 واحد اضافه می‌کنیم
 * تا پشته به حالت اولیه (قبل از اجرای تابع) برگردد.
 */

; همان‌طور که stp برای ذخیره کردن جفتیِ ریجیسترها در حافظه (پشته) بود، ldp برای پس گرفتن یا بازیابی آن‌ها استفاده می‌شود.

       /* بازیابی ریجیسترهای d14 و d15 از پشته */
       ldp d14, d15, [sp, #48]
       /* بازیابی ریجیسترهای d12 و d13 از پشته */
       ldp d12, d13, [sp, #32]
       /* بازیابی ریجیسترهای d10 و d11 از پشته */
       ldp d10, d11, [sp, #16]
       /* بازیابی d8 و d9 و برگرداندن پلاک پشته (Stack Pointer) به حالت اول (64 بایت عقب) */
       ldp d8, d9, [sp], #64

       /* بازگشت نهایی از تابع به محیط فراخوان  */
       ret