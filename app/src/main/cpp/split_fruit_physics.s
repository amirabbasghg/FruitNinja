/*
 * ============================================================================
 * نام تابع: calculate_split_velocities
 * هدف: محاسبه سرعت‌های جدید برای تکه‌های میوه پس از برش (انفجار جانبی)
 * ورودی‌ها:
 * x0 : آدرس بافر خروجی برای ذخیره نتایج (Pointer to results array)
 * s0 : سرعت افقی فعلی میوه (Current VX)
 * s1 : سرعت عمودی فعلی میوه (Current VY)
 * خروجی:
 * [x0]     : سرعت افقی تکه چپ
 * [x0 + 4] : سرعت افقی تکه راست
 * [x0 + 8] : سرعت عمودی جدید (پرتاب به بالا)
 * ============================================================================
 */

.text
.align 4
.global calculate_split_velocities

calculate_split_velocities:
    /* بارگذاری مقدار 10.0 (نیروی انفجار افقی) از قالب هگز به ریجیستر عمومی */
    mov w1, #0x41200000
    /* انتقال مقدار 10.0 به ریجیستر اعشاری s2 */
    fmov s2, w1

    /* بارگذاری مقدار 5.0 (نیروی کمکی برای پرتاب به بالا) در ریجیستر عمومی */
    mov w1, #0x40a00000
    /* انتقال مقدار 5.0 به ریجیستر اعشاری s3 */
    fmov s3, w1

    /* محاسبه سرعت تکه چپ: سرعت فعلی منهای نیروی انفجار (left_vx = vx - 10.0) */
    fsub s10, s0, s2

    /* محاسبه سرعت تکه راست: سرعت فعلی بعلاوه نیروی انفجار (right_vx = vx + 10.0) */
    fadd s11, s0, s2

    /* محاسبه سرعت عمودی جدید: کسر مقدار از vy برای پرتاب شدن به سمت بالا (new_vy = vy - 5.0) */
    /* نکته: در سیستم مختصات اندروید، مقادیر منفی Y به سمت بالا حرکت می‌کنند */
    fsub s12, s1, s3

    /* ذخیره سرعت افقی تکه چپ در اولین خانه آرایه خروجی */
    str s10, [x0]

    /* ذخیره سرعت افقی تکه راست در دومین خانه (آفست 4 بایتی) */
    str s11, [x0, #4]

    /* ذخیره سرعت عمودی جدید در سومین خانه (آفست 8 بایتی) */
    str s12, [x0, #8]

    /* بازگشت به تابع فراخوان */
    ret