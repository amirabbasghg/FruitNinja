// فایل split_physics.s
.text
.align 4
.global calculate_split_velocities

// ورودی‌ها:
// s0: سرعت افقی اصلی (velX)
// s1: سرعت عمودی اصلی (velY)
// خروجی:
// v0.s[0]: سرعت افقی نیمه چپ
// v0.s[1]: سرعت افقی نیمه راست
// v0.s[2]: سرعت عمودی هر دو نیمه (کمی به بالا پرتاب می‌شوند)

calculate_split_velocities:
    // تعریف نیروی پرتاب به طرفین (مثلاً ۱۰.۰)
    mov x0, #0x41200000        // مقدار Float برای 10.0 در قالب هگز
    fmov s2, w0                // s2 = 10.0 (Explosion Force)

    // نیمه چپ: سرعت اصلی منهای نیروی انفجار
    fsub s10, s0, s2           // velX_left = velX - 10.0

    // نیمه راست: سرعت اصلی به علاوه نیروی انفجار
    fadd s11, s0, s2           // velX_right = velX + 10.0

    // کمی پرتاب به سمت بالا برای جذابیت (کم کردن از velY چون جهت بالا منفی است)
    mov x1, #0x40A00000        // مقدار Float برای 5.0
    fmov s12, w1
    fsub s13, s1, s12           // velY_new = velY - 5.0

    // بسته‌بندی نتایج در یک وکتور برای بازگشت سریع
    ins v0.s[0], v10.s[0]
    ins v0.s[1], v11.s[0]
    ins v0.s[2], v13.s[0]

    ret