/*
 * ============================================================================
 * نام تابع: check_and_find_fruit_index
 * هدف: بررسی برخورد دایره‌ای با لیستی از اشیاء با استفاده از تکنیک NEON SIMD
 * * ورودی‌های دریافتی از سیستم (Calling Convention):
 * --------------------------------------------------
 * x0 : آدرس پایه بافر در حافظه (Pointer to Fruit Data)
 * x1 : تعداد کل میوه‌ها جهت پردازش (Total Count)
 * s0 : مختصات X مرکز دایره برخورد (Target X) -> بخشی از v0.s[0]
 * s1 : مختصات Y مرکز دایره برخورد (Target Y) -> بخشی از v1.s[0]
 * s2 : شعاع دایره برخورد (Radius)        -> بخشی از v2.s[0]
 * ============================================================================
 */
/* شروع بخش کد (Text Segment) */
.text

/* تراز کردن حافظه در مرزهای 4 بایتی برای بهینه‌سازی سرعت پردازنده */
.align 4

/* معرفی نام تابع به صورت سراسری برای دسترسی توسط کامپایلر C++ یا سیستم‌عامل */
.global check_and_find_fruit_index

check_and_find_fruit_index:
    /* بررسی شرط اولیه: اگر تعداد میوه‌ها (x1) صفر یا کمتر باشد، مستقیماً به پایان برو */
    cmp x1, #0
    /* پرش به بخش پایان در صورت عدم وجود میوه */
    ble no_hit

    /* محاسبه توان دوم شعاع (R^2) و ذخیره در s2 برای حذف نیاز به جذر گرفتن در محاسبات فاصله */
    fmul s2, s2, s2

    /* پخش کردن مختصات X هدف در تمام 4 بخش ریجیستر v0 برای محاسبات موازی */
    dup v0.4s, v0.s[0]

    /* پخش کردن مختصات Y هدف در تمام 4 بخش ریجیستر v1 برای محاسبات موازی */
    dup v1.4s, v1.s[0]

    /* پخش کردن مقدار R^2 در تمام 4 بخش ریجیستر v2 جهت مقایسه موازی با فواصل */
    dup v2.4s, v2.s[0]

    /* مقداردهی اولیه شمارنده ایندکس (Index Counter) از صفر */
    mov x3, #0

    /* کپی کردن آدرس پایه بافر از x0 به x4 برای استفاده به عنوان پوینتر متحرک در طول حلقه */
    mov x4, x0

    /* قرار دادن عدد 4 در x10: فاصله بایت‌ها برای پرش از X به Y در هر میوه (هر فلوت 4 بایت است) */
    mov x10, #4

    /* قرار دادن عدد 16 در x11: فاصله بایت‌ها برای پرش از Y میوه فعلی به X میوه بعدی (20 بایت کل ساختار) */
    mov x11, #16

neon_loop:
    /* محاسبه تعداد میوه‌های باقی‌مانده: (تعداد کل - ایندکس فعلی) */
    sub x5, x1, x3

    /* مقایسه باقی‌مانده با عدد 4 (چون NEON در هر دور 4 تا را پردازش می‌کند) */
    cmp x5, #4

    /* اگر کمتر از 4 میوه مانده، به حلقه معمولی (Scalar) برو تا دانه‌دانه بررسی شوند */
    blt scalar_loop


/*
 * تحلیل دستور کلیدی ld1 در معماری ARM64 NEON:
 * فرمت: ld1 {v3.s}[0], [x4], x10
 * * ۱. مقصد {v3.s}[0]:
 * - v3: ریجیستر ۱۲۸ بیتی مقصد (معادل XMM در x86).
 * - .s: نوع داده Single-precision (32-bit float).
 * - [0]: بارگذاری فقط در Lane شماره ۰؛ سایر لاین‌ها (۱، ۲، ۳) دست‌نخورده می‌مانند.
 * * ۲. منبع [x4]:
 * - خواندن دیتا از آدرس حافظه‌ای که در ریجیستر x4 است (معادل MOVSS در x86).
 * * ۳. بروزرسانی پسا-ایندکس (Post-Index Update) , x10:
 * - بلافاصله پس از لود، مقدار ریجیستر x10 به x4 اضافه می‌شود (x4 = x4 + x10).
 * - این کار در همان سیکل لود انجام شده و نیاز به دستور ADD جداگانه را حذف می‌کند.
 * * ۴. چرا از این روش استفاده کردیم؟
 * - ساختار میوه ۲۰ بایتی است (X, Y, Z, W, Type). چون داده‌ها (Xها و Yها) در حافظه
 * پشت سر هم نیستند، نمی‌توان ۴ تا را یکجا لود کرد.
 * - با این دستور: ابتدا X لود شده و پوینتر ۴ واحد جلو می‌رود (روی Y).
 * - سپس Y لود شده و پوینتر ۱۶ واحد دیگر جلو می‌رود تا روی X میوه بعدی قرار بگیرد.
 */
    /* --- میوه اول --- */
        /* بارگذاری X0 در خانه اول v3 و پرش پوینتر به اندازه 4 بایت (رفتن روی Y0) */
        ld1 {v3.s}[0], [x4], x10
        /* بارگذاری Y0 در خانه اول v4 و پرش پوینتر به اندازه 16 بایت (رفتن روی X میوه بعدی) */
        ld1 {v4.s}[0], [x4], x11

        /* --- میوه دوم --- */
        /* بارگذاری X1 در خانه دوم v3 و پرش به Y1 */
        ld1 {v3.s}[1], [x4], x10
        /* بارگذاری Y1 در خانه دوم v4 و پرش به X میوه سوم */
        ld1 {v4.s}[1], [x4], x11

        /* --- میوه سوم --- */
        ld1 {v3.s}[2], [x4], x10
        ld1 {v4.s}[2], [x4], x11

        /* --- میوه چهارم --- */
        ld1 {v3.s}[3], [x4], x10
        ld1 {v4.s}[3], [x4], x11

/* --- محاسبات فاصله (ریاضیات برداری SIMD) --- */

    /* محاسبه اختلاف X میوه‌ها با X هدف (dx = FruitX - TargetX) برای هر 4 لاین */
    fsub v3.4s, v3.4s, v0.4s

    /* محاسبه اختلاف Y میوه‌ها با Y هدف (dy = FruitY - TargetY) برای هر 4 لاین */
    fsub v4.4s, v4.4s, v1.4s

    /* محاسبه مجذور اختلاف Xها (v3 = dx * dx) */
    fmul v3.4s, v3.4s, v3.4s

    /* محاسبه مجذور Yها و جمع با نتیجه قبلی (v3 = dx^2 + dy^2) در یک مرحله سریع */
    fmla v3.4s, v4.4s, v4.4s

    /* --- بررسی برخورد (فیلتر کردن نتایج) --- */

    /* مقایسه شعاع به توان 2 با فاصله به توان 2؛ ایجاد ماسک برخورد (True/False) در v5 */
    fcmgt v5.4s, v2.4s, v3.4s

    /* پیدا کردن بزرگترین مقدار در کل بردار؛ اگر حتی یک لاین برخورد داشته باشد نتیجه غیرصفر است */
    umaxv s6, v5.4s

    /* انتقال نتیجه مقایسه از ریجیستر اعشاری به ریجیستر صحیح برای بررسی شرطی */
    fmov w6, s6

    /* اگر هیچ برخوردی در این 4 مورد نبود (w6 == 0)، بپر به بخش میوه‌های بعدی */
    cbz w6, next_neon

    /* --- پیدا کردن لاین (خانه) دقیق برخورد از بین این 4 مورد --- */

    /* استخراج مقدار خانه اول (لاین 0) از ماسک برخورد */
    umov w6, v5.s[0]
    /* اگر این خانه غیرصفر بود، یعنی برخورد با میوه اول بوده است */
    cbnz w6, hit_0

    /* استخراج مقدار خانه دوم (لاین 1) */
    umov w6, v5.s[1]
    /* اگر غیرصفر بود، یعنی برخورد با میوه دوم بوده است */
    cbnz w6, hit_1

    /* استخراج مقدار خانه سوم (لاین 2) */
    umov w6, v5.s[2]
    /* اگر غیرصفر بود، یعنی برخورد با میوه سوم بوده است */
    cbnz w6, hit_2

    /* اگر هیچکدام از موارد بالا نبود، قطعاً میوه چهارم برخورد کرده؛ ایندکس را محاسبه کن */
    add x0, x3, #3
    /* خروج از تابع با مقدار ایندکس نهایی */
    ret

/* بخش‌های بازگشت مقدار نهایی بر اساس لاین پیدا شده */
hit_0: mov x0, x3; ret           /* بازگشت ایندکس شروع بلوک */
hit_1: add x0, x3, #1; ret       /* بازگشت ایندکس دوم */
hit_2: add x0, x3, #2; ret       /* بازگشت ایندکس سوم */

next_neon:
    /* افزایش 4 واحدی شمارنده کل برای رفتن سراغ 4 میوه بعدی در بافر */
    add x3, x3, #4
    /* پرش به ابتدای حلقه NEON برای تکرار فرآیند */
    b neon_loop

/* --- حلقه پردازش تکی (Scalar Loop) برای میوه‌های باقی‌مانده --- */
scalar_loop:
    /* مقایسه ایندکس فعلی با تعداد کل میوه‌ها جهت اطمینان از پایان نیافتن لیست */
    cmp x3, x1
    /* اگر تمام میوه‌ها بررسی شده‌اند و برخوردی نبوده، به بخش no_hit برو */
    b.ge no_hit

    /* بارگذاری مختصات X میوه فعلی از حافظه (آدرس فعلی در x4) */
    ldr s3, [x4]
    /* بارگذاری مختصات Y میوه فعلی (که با فاصله 4 بایتی بعد از X قرار دارد) */
    ldr s4, [x4, #4]

    /* محاسبه تفاضل X میوه با X هدف (dx = FruitX - TargetX) */
    fsub s3, s3, s0
    /* محاسبه تفاضل Y میوه با Y هدف (dy = FruitY - TargetY) */
    fsub s4, s4, s1

    /* محاسبه مجذور تفاضل X (s3 = dx * dx) */
    fmul s3, s3, s3
    /* محاسبه مجذور Y و جمع با نتیجه قبلی (s3 = dx^2 + dy^2) در یک مرحله */
    fmadd s3, s4, s4, s3

    /* مقایسه فاصله به توان 2 با شعاع به توان 2 (s2) */
    fcmpe s3, s2
    /* اگر نتیجه منفی (Minus) باشد یعنی فاصله < شعاع است؛ پس برخورد رخ داده */
    b.mi found_scalar

    /* افزایش یک واحدی شمارنده ایندکس برای بررسی میوه بعدی */
    add x3, x3, #1
    /* پیشروی 20 بایتی آدرس حافظه برای رسیدن به داده‌های میوه بعدی */
    add x4, x4, #20
    /* تکرار حلقه برای میوه بعدی در لیست باقی‌مانده‌ها */
    b scalar_loop

/* --- بخش خروجی‌های نهایی تابع --- */

found_scalar:
    /* کپی کردن شماره میوه (ایندکس) پیدا شده در x0 جهت بازگشت به برنامه اصلی */
    mov x0, x3
    /* خروج از تابع */
    ret

no_hit:
    /* قرار دادن مقدار 1- در x0 به نشانه عدم پیدا شدن هرگونه برخورد */
    mov x0, #-1
    /* خروج از تابع */
    ret