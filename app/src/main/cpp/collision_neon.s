/*
 * ============================================================================
 * نام تابع: check_and_find_fruit_index
 * هدف: بررسی برخورد دایره‌ای با لیستی از اشیاء با استفاده از تکنیک NEON SIMD
 * * ورودی‌های دریافتی از سیستم (Calling Convention):
 * --------------------------------------------------
 * x0 : آدرس پایه بافر در حافظه (Pointer to Fruit Data)
 * x1 : تعداد کل میوه‌ها جهت پردازش (Total Count)
 * s0 : مختصات X مرکز دایره برخورد (Target X) -> بخشی از v0.s[0]
 * s1 : مختصات Y مرکز دایره برخورد (Target Y) -> بخشی از v1.s[0]
 * s2 : شعاع دایره برخورد (Radius)        -> بخشی از v2.s[0]
 * ============================================================================
 */
/* شروع بخش کد (Text Segment) */
.text

/* تراز کردن حافظه در مرزهای 4 بایتی برای بهینه‌سازی سرعت پردازنده */
.align 4

/* معرفی نام تابع به صورت سراسری برای دسترسی توسط کامپایلر C++ یا سیستم‌عامل */
.global check_and_find_fruit_index

check_and_find_fruit_index:
    /* بررسی شرط اولیه: اگر تعداد میوه‌ها (x1) صفر یا کمتر باشد، مستقیماً به پایان برو */
    cmp x1, #0
    /* پرش به بخش پایان در صورت عدم وجود میوه */
    ble no_hit

    /* محاسبه توان دوم شعاع (R^2) و ذخیره در s2 برای حذف نیاز به جذر گرفتن در محاسبات فاصله */
    fmul s2, s2, s2

    /* پخش کردن مختصات X هدف در تمام 4 بخش ریجیستر v0 برای محاسبات موازی */
    dup v0.4s, v0.s[0]

    /* پخش کردن مختصات Y هدف در تمام 4 بخش ریجیستر v1 برای محاسبات موازی */
    dup v1.4s, v1.s[0]

    /* پخش کردن مقدار R^2 در تمام 4 بخش ریجیستر v2 جهت مقایسه موازی با فواصل */
    dup v2.4s, v2.s[0]

    /* مقداردهی اولیه شمارنده ایندکس (Index Counter) از صفر */
    mov x3, #0

    /* کپی کردن آدرس پایه بافر از x0 به x4 برای استفاده به عنوان پوینتر متحرک در طول حلقه */
    mov x4, x0

    /* قرار دادن عدد 4 در x10: فاصله بایت‌ها برای پرش از X به Y در هر میوه (هر فلوت 4 بایت است) */
    mov x10, #4

    /* قرار دادن عدد 16 در x11: فاصله بایت‌ها برای پرش از Y میوه فعلی به X میوه بعدی (20 بایت کل ساختار) */
    mov x11, #16

neon_loop:
    /* محاسبه تعداد میوه‌های باقی‌مانده: (تعداد کل - ایندکس فعلی) */
    sub x5, x1, x3

    /* مقایسه باقی‌مانده با عدد 4 (چون NEON در هر دور 4 تا را پردازش می‌کند) */
    cmp x5, #4

    /* اگر کمتر از 4 میوه مانده، به حلقه معمولی (Scalar) برو تا دانه‌دانه بررسی شوند */
    blt scalar_loop


/*
 * تحلیل دستور کلیدی ld1 در معماری ARM64 NEON:
 * فرمت: ld1 {v3.s}[0], [x4], x10
 * * ۱. مقصد {v3.s}[0]:
 * - v3: ریجیستر ۱۲۸ بیتی مقصد (معادل XMM در x86).
 * - .s: نوع داده Single-precision (32-bit float).
 * - [0]: بارگذاری فقط در Lane شماره ۰؛ سایر لاین‌ها (۱، ۲، ۳) دست‌نخورده می‌مانند.
 * * ۲. منبع [x4]:
 * - خواندن دیتا از آدرس حافظه‌ای که در ریجیستر x4 است (معادل MOVSS در x86).
 * * ۳. بروزرسانی پسا-ایندکس (Post-Index Update) , x10:
 * - بلافاصله پس از لود، مقدار ریجیستر x10 به x4 اضافه می‌شود (x4 = x4 + x10).
 * - این کار در همان سیکل لود انجام شده و نیاز به دستور ADD جداگانه را حذف می‌کند.
 * * ۴. چرا از این روش استفاده کردیم؟
 * - ساختار میوه ۲۰ بایتی است (X, Y, Z, W, Type). چون داده‌ها (Xها و Yها) در حافظه
 * پشت سر هم نیستند، نمی‌توان ۴ تا را یکجا لود کرد.
 * - با این دستور: ابتدا X لود شده و پوینتر ۴ واحد جلو می‌رود (روی Y).
 * - سپس Y لود شده و پوینتر ۱۶ واحد دیگر جلو می‌رود تا روی X میوه بعدی قرار بگیرد.
 */
    /* --- میوه اول --- */
        /* بارگذاری X0 در خانه اول v3 و پرش پوینتر به اندازه 4 بایت (رفتن روی Y0) */
        ld1 {v3.s}[0], [x4], x10
        /* بارگذاری Y0 در خانه اول v4 و پرش پوینتر به اندازه 16 بایت (رفتن روی X میوه بعدی) */
        ld1 {v4.s}[0], [x4], x11

        /* --- میوه دوم --- */
        /* بارگذاری X1 در خانه دوم v3 و پرش به Y1 */
        ld1 {v3.s}[1], [x4], x10
        /* بارگذاری Y1 در خانه دوم v4 و پرش به X میوه سوم */
        ld1 {v4.s}[1], [x4], x11

        /* --- میوه سوم --- */
        ld1 {v3.s}[2], [x4], x10
        ld1 {v4.s}[2], [x4], x11

        /* --- میوه چهارم --- */
        ld1 {v3.s}[3], [x4], x10
        ld1 {v4.s}[3], [x4], x11

    // محاسبات فاصله
    fsub v3.4s, v3.4s, v0.4s
    fsub v4.4s, v4.4s, v1.4s
    fmul v3.4s, v3.4s, v3.4s
    fmla v3.4s, v4.4s, v4.4s

    // بررسی برخورد
    fcmgt v5.4s, v2.4s, v3.4s
    umaxv s6, v5.4s
    fmov w6, s6
    cbz w6, next_neon

    // پیدا کردن لاین دقیق برخورد
    umov w6, v5.s[0]
    cbnz w6, hit_0
    umov w6, v5.s[1]
    cbnz w6, hit_1
    umov w6, v5.s[2]
    cbnz w6, hit_2
    add x0, x3, #3
    ret

hit_0: mov x0, x3; ret
hit_1: add x0, x3, #1; ret
hit_2: add x0, x3, #2; ret

next_neon:
    add x3, x3, #4
    b neon_loop

scalar_loop:
    cmp x3, x1
    b.ge no_hit
    ldr s3, [x4]
    ldr s4, [x4, #4]
    fsub s3, s3, s0
    fsub s4, s4, s1
    fmul s3, s3, s3
    fmadd s3, s4, s4, s3
    fcmpe s3, s2
    b.mi found_scalar
    add x3, x3, #1
    add x4, x4, #20
    b scalar_loop

found_scalar:
    mov x0, x3
    ret

no_hit:
    mov x0, #-1
    ret