/*
 * ============================================================================
 * نام تابع: find_fallen_fruit_index_neon
 * هدف: پیدا کردن ایندکس اولین میوه‌ای که از "خط مرگ" (Death Line) عبور کرده است.
 * ورودی‌ها:
 * x0 : آدرس شروع بافر میوه‌ها (هر میوه 20 بایت)
 * x1 : تعداد کل میوه‌ها (Count)
 * s0 : مقدار Y خط مرگ (Death Line)
 * ============================================================================
 */

.text
.align 4
.global find_fallen_fruit_index_neon

find_fallen_fruit_index_neon:
    /* کپی کردن مقدار خط مرگ در تمام 4 لاین v0 برای مقایسه همزمان با 4 میوه */
    dup v0.4s, v0.s[0]

    /* مقداردهی اولیه به شمارنده ایندکس (Index) از صفر */
    mov x2, #0

    /* بررسی اولیه: اگر تعداد میوه‌ها کمتر از 4 است، مستقیماً به بررسی تکی (Serial) برو */
    cmp x1, #4
    b.lt serial_check

parallel_loop:
    /* محاسبه تعداد میوه‌های باقی‌مانده (Count - CurrentIndex) */
    sub x3, x1, x2
    /* اگر کمتر از 4 میوه برای بررسی باقی مانده، حلقه NEON را تمام کن */
    cmp x3, #4
    b.lt serial_check

    /* محاسبه آفست حافظه: (ایندکس فعلی * 20 بایت اندازه هر ساختار) */
    mov x4, #20
    mul x5, x2, x4
    /* محاسبه آدرس دقیق شروع در رم: (آدرس پایه x0 + آفست محاسبه شده x5) */
    add x5, x0, x5

    /* بارگذاری مختصات Y چهار میوه به صورت مجزا (Y در آفست 4 هر میوه است) */
    ldr s1, [x5, #4]            /* Y میوه اول */
    ldr s2, [x5, #24]           /* Y میوه دوم (4 + 20 بایت فاصله) */
    ldr s3, [x5, #44]           /* Y میوه سوم (24 + 20 بایت فاصله) */
    ldr s4, [x5, #64]           /* Y میوه چهارم (44 + 20 بایت فاصله) */

    /* بسته‌بندی (Packing) مقادیر Y لود شده درون ریجیستر برداری v1 */
    /* مقدار s1 از قبل در v1.s[0] قرار دارد */
    mov v1.s[1], v2.s[0]
    mov v1.s[2], v3.s[0]
    mov v1.s[3], v4.s[0]

    /* مقایسه موازی: آیا مختصات Y این 4 میوه بزرگتر از خط مرگ (v0) است؟ */
    fcmgt v5.4s, v1.4s, v0.4s

    /* تجمیع نتایج مقایسه: پیدا کردن بزرگترین مقدار در لاین‌های v5 */
    umaxv s6, v5.4s
    /* انتقال نتیجه به ریجیستر عمومی جهت بررسی شرطی */
    fmov w6, s6
    /* اگر w6 غیرصفر باشد، یعنی حداقل یکی از این 4 میوه سقوط کرده است */
    cmp w6, #0
    b.ne find_exact_index

    /* اگر هیچکدام سقوط نکرده بودند، ایندکس را 4 واحد افزایش بده */
    add x2, x2, #4
    /* تکرار حلقه برای 4 میوه بعدی */
    b parallel_loop

serial_check:
    /* بررسی اینکه آیا از تعداد کل میوه‌ها فراتر رفته‌ایم یا خیر */
    cmp x2, x1
    b.ge none_found

    /* محاسبه آدرس میوه فعلی برای بررسی تکی (ایندکس * 20 + آدرس پایه) */
    mov x4, #20
    mul x5, x2, x4
    add x5, x0, x5
    /* بارگذاری مقدار Y میوه فعلی در ریجیستر s10 */
    ldr s10, [x5, #4]

    /* مقایسه مقدار Y با خط مرگ اصلی (s0) */
    fcmp s10, s0
    /* اگر Y > DeathLine بود، یعنی میوه سقوط کرده و ایندکس آن را پیدا کردیم */
    b.gt found_it

    /* رفتن به میوه بعدی در لیست (بررسی یکی‌یکی) */
    add x2, x2, #1
    b serial_check

find_exact_index:
    /* وقتی NEON برخوردی پیدا می‌کند، به اینجا می‌آییم تا با دقت تکی، شماره دقیق را پیدا کنیم */
    b serial_check

found_it:
    /* قرار دادن شماره ایندکس پیدا شده در x0 برای بازگشت به برنامه اصلی */
    mov x0, x2
    ret

none_found:
    /* اگر تمام لیست بررسی شد و هیچ میوه‌ای سقوط نکرده بود، مقدار 1- برگردان */
    mov x0, #-1
    ret